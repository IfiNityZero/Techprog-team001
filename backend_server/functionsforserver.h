#ifndef FUNCTIONSFORSERVER_H
#define FUNCTIONSFORSERVER_H

#include <QString>

/**
 * @file functionsforserver.h
 * @brief Заголовочный файл с объявлениями всех алгоритмов сервера.
 * @author Усачев Тимофей, Корвяков Святогор, Гусейнов Артем
 * @date 2026
 *
 * Содержит объявления функций для:
 * - Парсинга команд от клиента
 * - Шифра Виженера (шифрование/дешифрование)
 * - Хеширования SHA-384
 * - Метода хорд (нахождение корня уравнения)
 * - Стеганографии (LSB в BMP)
 */

/**
 * @brief Главная функция разбора команды от клиента.
 *
 * Принимает строку запроса, разбивает её по символу ':',
 * определяет команду и вызывает соответствующую функцию.
 *
 * Поддерживаемые команды:
 * - vigenere_encrypt:ТЕКСТ:КЛЮЧ
 * - vigenere_decrypt:ТЕКСТ:КЛЮЧ
 * - sha384:ТЕКСТ
 * - chord:A:B:EPS
 * - stego_encode:ПУТЬ:СООБЩЕНИЕ
 * - stego_decode:ПУТЬ
 *
 * @param request Строка запроса от клиента
 * @return Строка с результатом или "error" при ошибке
 */
QString parsing(QString request);

/**
 * @brief Шифрование текста методом Виженера.
 *
 * Полиалфавитный шифр подстановки. Каждая буква текста
 * сдвигается в алфавите на величину, определяемую
 * соответствующей буквой ключа.
 *
 * Формула: C[i] = (P[i] + K[i % len(K)]) % 26
 *
 * Работает только с латинскими буквами (A-Z, a-z).
 * Регистр символов сохраняется.
 * Цифры, пробелы и знаки препинания не изменяются.
 *
 * @param text Исходный текст для шифрования
 * @param key Ключ шифрования (латинские буквы)
 * @return Зашифрованный текст или "error" если ключ пустой
 *
 * @example
 * vigenereEncrypt("HELLO", "KEY") == "RIJVS"
 */
QString vigenereEncrypt(const QString &text, const QString &key);

/**
 * @brief Дешифрование текста методом Виженера.
 *
 * Обратная операция к vigenereEncrypt.
 * Формула: P[i] = (C[i] - K[i % len(K)] + 26) % 26
 *
 * @param text Зашифрованный текст
 * @param key Ключ шифрования (тот же что при шифровании)
 * @return Расшифрованный текст или "error" если ключ пустой
 *
 * @example
 * vigenereDecrypt("RIJVS", "KEY") == "HELLO"
 */
QString vigenereDecrypt(const QString &text, const QString &key);

/**
 * @brief Вычисление SHA-384 хеша строки.
 *
 * Использует Qt класс QCryptographicHash для вычисления
 * криптографического хеша SHA-384.
 *
 * Свойства:
 * - Длина результата всегда 96 символов (384 бита в hex)
 * - Одностороння функция — по хешу нельзя восстановить текст
 * - Лавинный эффект — малое изменение входа даёт другой хеш
 *
 * @param text Входная строка для хеширования
 * @return Хеш в виде hex-строки длиной 96 символов
 *
 * @example
 * sha384("abc") == "cb00753f45a35e8bb5a03d699ac65007..."
 */
QString sha384(const QString &text);

/**
 * @brief Нахождение корня уравнения методом хорд.
 *
 * Итерационный численный метод нахождения корня уравнения
 * f(x) = x^3 - x - 2 = 0 на отрезке [a, b].
 *
 * Условие применения: f(a) * f(b) < 0
 * (функция должна иметь разные знаки на концах отрезка).
 *
 * Формула итерации:
 * x = a - f(a) * (b - a) / (f(b) - f(a))
 *
 * @param a Левая граница отрезка
 * @param b Правая граница отрезка
 * @param eps Точность вычисления (например, 1e-6)
 * @return Приближённое значение корня или NaN если корня нет
 *
 * @example
 * chordMethod(1.0, 2.0, 1e-6) ≈ 1.5213797
 */
double chordMethod(double a, double b, double eps);

/**
 * @brief Обёртка метода хорд для работы со строковыми аргументами.
 *
 * Конвертирует строковые аргументы в числа и вызывает chordMethod.
 * Используется в функции parsing() для обработки команды "chord".
 *
 * @param a Левая граница в виде строки
 * @param b Правая граница в виде строки
 * @param eps Точность в виде строки
 * @return Результат в виде строки или "error" при некорректных данных
 */
QString chordMethodStr(const QString &a, const QString &b, const QString &eps);

/**
 * @brief Внедрение текстового сообщения в BMP изображение (стеганография).
 *
 * Метод LSB (Least Significant Bit) — младший бит каждого байта
 * пикселя заменяется на бит скрытого сообщения.
 *
 * Структура данных в файле:
 * - Первые 54 байта: заголовок BMP (не изменяется)
 * - Следующие 32 бита: длина сообщения
 * - Затем: биты самого сообщения (по 1 биту на байт пикселя)
 *
 * Визуально изображение практически не изменяется,
 * так как изменение 1 бита из 8 незаметно для глаза.
 *
 * @param imagePath Абсолютный путь к BMP файлу
 * @param message Текстовое сообщение для внедрения
 * @return "ok: message encoded" при успехе или строку с ошибкой
 */
QString stegoEncode(const QString &imagePath, const QString &message);

/**
 * @brief Извлечение скрытого сообщения из BMP изображения.
 *
 * Обратная операция к stegoEncode.
 * Читает младшие биты байт пикселей и восстанавливает сообщение.
 *
 * @param imagePath Абсолютный путь к BMP файлу с внедрённым сообщением
 * @return Извлечённое текстовое сообщение или строку с ошибкой
 */
QString stegoDecode(const QString &imagePath);

#endif // FUNCTIONSFORSERVER_H
