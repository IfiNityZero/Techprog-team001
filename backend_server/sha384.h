#ifndef SHA384_H
#define SHA384_H

/**
 * @file sha384.h
 * @brief Собственная реализация алгоритма хеширования SHA-384.
 * @author Усачев Тимофей, Корвяков Святогор, Гусейнов Артем
 * @date 2026
 *
 * Реализация SHA-384 без использования сторонних библиотек.
 * SHA-384 входит в семейство SHA-2 и является усечённой
 * версией SHA-512 с другими начальными значениями.
 *
 * Характеристики:
 * - Длина хеша: 384 бита (96 символов в hex)
 * - Размер блока: 1024 бита (128 байт)
 * - Число раундов: 80
 * - Операции: AND, OR, XOR, NOT, сдвиги, сложение по модулю 2^64
 */

#include <QString>
#include <QByteArray>
#include <cstdint>

/**
 * @brief Класс реализующий алгоритм хеширования SHA-384.
 *
 * Все методы статические — не нужно создавать объект класса.
 *
 * Алгоритм состоит из трёх этапов:
 * 1. Подготовка сообщения (padding)
 * 2. Разбивка на блоки по 1024 бита
 * 3. Обработка каждого блока (80 раундов)
 */
class SHA384
{
public:
    /**
     * @brief Вычислить SHA-384 хеш строки.
     *
     * @param input Входная строка
     * @return Хеш в виде hex-строки длиной 96 символов
     */
    static QString hash(const QString &input);

    /**
     * @brief Вычислить SHA-384 хеш байтового массива.
     *
     * @param data Входные данные
     * @return Хеш в виде hex-строки длиной 96 символов
     */
    static QString hash(const QByteArray &data);

private:
    /**
     * @brief Циклический сдвиг вправо 64-битного числа.
     *
     * ROTR(x, n) = (x >> n) | (x << (64 - n))
     *
     * @param x Число для сдвига
     * @param n Количество бит сдвига
     * @return Результат циклического сдвига
     */
    static uint64_t rotr64(uint64_t x, int n);

    /**
     * @brief Функция Ch (Choice) — выбор.
     *
     * Ch(x, y, z) = (x AND y) XOR (NOT x AND z)
     * Если бит x = 1, берём бит из y, иначе из z.
     *
     * @param x, y, z Входные 64-битные числа
     * @return Результат функции Ch
     */
    static uint64_t ch(uint64_t x, uint64_t y, uint64_t z);

    /**
     * @brief Функция Maj (Majority) — большинство.
     *
     * Maj(x, y, z) = (x AND y) XOR (x AND z) XOR (y AND z)
     * Возвращает бит который встречается чаще всего.
     *
     * @param x, y, z Входные 64-битные числа
     * @return Результат функции Maj
     */
    static uint64_t maj(uint64_t x, uint64_t y, uint64_t z);

    /**
     * @brief Функция Σ0 (Sigma0) — большая сигма 0.
     *
     * Σ0(x) = ROTR(x,28) XOR ROTR(x,34) XOR ROTR(x,39)
     *
     * @param x Входное 64-битное число
     * @return Результат функции Σ0
     */
    static uint64_t sigma0(uint64_t x);

    /**
     * @brief Функция Σ1 (Sigma1) — большая сигма 1.
     *
     * Σ1(x) = ROTR(x,14) XOR ROTR(x,18) XOR ROTR(x,41)
     *
     * @param x Входное 64-битное число
     * @return Результат функции Σ1
     */
    static uint64_t sigma1(uint64_t x);

    /**
     * @brief Функция σ0 (sigma0) — малая сигма 0.
     *
     * σ0(x) = ROTR(x,1) XOR ROTR(x,8) XOR (x >> 7)
     * Используется при расширении расписания сообщения.
     *
     * @param x Входное 64-битное число
     * @return Результат функции σ0
     */
    static uint64_t gamma0(uint64_t x);

    /**
     * @brief Функция σ1 (sigma1) — малая сигма 1.
     *
     * σ1(x) = ROTR(x,19) XOR ROTR(x,61) XOR (x >> 6)
     * Используется при расширении расписания сообщения.
     *
     * @param x Входное 64-битное число
     * @return Результат функции σ1
     */
    static uint64_t gamma1(uint64_t x);

    /**
     * @brief Обработать один 1024-битный блок сообщения.
     *
     * Выполняет 80 раундов преобразований над блоком,
     * обновляет значения переменных состояния h0-h7.
     *
     * @param block Указатель на блок из 16 64-битных слов (128 байт)
     * @param h Массив из 8 переменных состояния (изменяется)
     */
    static void processBlock(const uint64_t *block, uint64_t h[8]);

    /// Таблица констант K (первые 80 простых чисел, дробные части кубических корней)
    static const uint64_t K[80];
};

#endif // SHA384_H
